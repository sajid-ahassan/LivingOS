class RemediationNotFoundError(ValueError):
    pass


class RemediationConflictError(ValueError):
    pass


def _resolve_manager(db: Session, case: Case) -> Person:
    subject = db.get(Person, case.subject_person_id)
    if subject is None:
        raise RemediationConflictError("Case subject does not exist.")

    manager_id = subject.manager_id or (case.case_facts or {}).get("manager_id")
    if not manager_id:
        raise RemediationConflictError(
            "A line manager is required for the regenerated plan approval."
        )

    manager = db.get(Person, UUID(str(manager_id)))
    if manager is None:
        raise RemediationConflictError("Assigned line manager does not exist.")

    return manager


def regenerate_plan_for_impact(
    db: Session,
    impact_id: UUID,
    request: RegenerateImpactRequest,
) -> RegenerateImpactResponse:
    impact = db.get(PolicyImpact, impact_id)
    if impact is None:
        raise RemediationNotFoundError(
            f"Policy impact does not exist: {impact_id}"
        )

    if impact.target_type != PolicyImpactTargetType.PLAN:
        raise RemediationConflictError(
            "REGENERATE remediation is valid only for PLAN impacts."
        )

    if impact.recommended_action != ImpactRecommendedAction.REGENERATE:
        raise RemediationConflictError(
            f"Impact recommends {impact.recommended_action.value}, not REGENERATE."
        )

    if impact.status != ImpactState.OPEN:
        raise RemediationConflictError(
            f"Impact is already {impact.status.value}."
        )

    stale_plan = db.get(CasePlan, impact.target_id)
    if stale_plan is None:
        raise RemediationNotFoundError(
            f"Impacted plan does not exist: {impact.target_id}"
        )

    case = db.get(Case, stale_plan.case_id)
    if case is None:
        raise RemediationNotFoundError(
            f"Case does not exist: {stale_plan.case_id}"
        )

    if stale_plan.status != PlanState.STALE:
        raise RemediationConflictError(
            f"Impacted plan must be STALE, not {stale_plan.status.value}."
        )

    if case.status != CaseState.PAUSED:
        raise RemediationConflictError(
            f"Impacted case must be PAUSED, not {case.status.value}."
        )

    if any(
        action.status in {
            ActionState.DISPATCHED,
            ActionState.SUCCEEDED,
            ActionState.VERIFIED,
        }
        for action in stale_plan.actions
    ):
        raise RemediationConflictError(
            "Cannot automatically regenerate after execution has started."
        )

    resolver = db.get(Person, request.resolved_by)
    if resolver is None:
        raise RemediationConflictError("Remediation resolver does not exist.")

    manager = _resolve_manager(db, case)

    original_case_status = case.status
    impact.status = ImpactState.REMEDIATING

    try:
        # Policy retrieval is intentionally allowed only in PLANNING.
        # If generation/validation fails, the transaction rolls back and
        # the case remains PAUSED.
        case.status = CaseState.PLANNING
        db.flush()

        policy_context = retrieve_case_policy_context(db, case)
        generated_plan = generate_case_plan(
            db,
            case,
            policy_context,
        )

        new_plan = CasePlan(
            case_id=case.id,
            revision=get_next_plan_revision(db, case.id),
            status=PlanState.PENDING_APPROVAL,
            summary=generated_plan.summary,
            plan_data=jsonable_encoder(generated_plan.model_dump()),
            parent_plan_id=stale_plan.id,
            correction_summary=(
                "Regenerated by Policy Change Guardian after policy impact "
                f"{impact.id}. {request.comment.strip()}"
            ),
        )
        db.add(new_plan)
        db.flush()

        db.add_all(
            [
                build_case_action(
                    case=case,
                    plan=new_plan,
                    action=action,
                )
                for action in generated_plan.actions
            ]
        )

        db.add_all(
            build_policy_links(
                db,
                new_plan,
                generated_plan,
                policy_context,
            )
        )

        stale_plan.status = PlanState.SUPERSEDED

        for action in stale_plan.actions:
            if action.status in {
                ActionState.PENDING,
                ActionState.FAILED,
                ActionState.RETRYING,
            }:
                action.status = ActionState.SKIPPED
                action.error_message = (
                    "Stale plan superseded by Policy Change Guardian remediation."
                )

        old_approval = db.scalar(
            select(Approval).where(
                Approval.target_type == ApprovalTargetType.PLAN,
                Approval.target_id == stale_plan.id,
                Approval.status == ApprovalState.PENDING,
            )
        )
        if old_approval is not None:
            old_approval.status = ApprovalState.REJECTED
            old_approval.comment = (
                "Plan became stale after a policy version change."
            )

        approval = Approval(
            target_type=ApprovalTargetType.PLAN,
            target_id=new_plan.id,
            requested_by=case.created_by_id,
            assigned_to=manager.id,
            status=ApprovalState.PENDING,
        )
        db.add(approval)

        case.status = CaseState.PENDING_APPROVAL
        case.failure_reason = None

        impact.status = ImpactState.RESOLVED
        impact.resolved_by = request.resolved_by

        db.flush()

        evidence_ids = sorted(
            {
                evidence_id
                for action in generated_plan.actions
                for evidence_id in action.evidence_ids
            }
        )

        record_audit_event(
            db,
            actor_type=AuditActorType.USER,
            actor_id=request.resolved_by,
            event_type="POLICY_IMPACT_REGENERATED",
            entity_type="policy_impact",
            entity_id=impact.id,
            before_data={
                "case_status": original_case_status.value,
                "stale_plan_id": str(stale_plan.id),
                "stale_plan_status": PlanState.STALE.value,
            },
            after_data={
                "new_plan_id": str(new_plan.id),
                "new_revision": new_plan.revision,
                "new_plan_status": new_plan.status.value,
                "case_status": case.status.value,
                "approval_id": str(approval.id),
            },
            evidence_data={
                "comment": request.comment.strip(),
                "current_evidence_ids": evidence_ids,
            },
            correlation_id=case.id,
        )

        db.commit()
        db.refresh(impact)
        db.refresh(stale_plan)
        db.refresh(new_plan)
        db.refresh(approval)
        db.refresh(case)

        return RegenerateImpactResponse(
            impact_id=impact.id,
            impact_status=impact.status,
            stale_plan_id=stale_plan.id,
            stale_plan_status=stale_plan.status,
            new_plan_id=new_plan.id,
            new_revision=new_plan.revision,
            new_plan_status=new_plan.status,
            approval_id=approval.id,
            approval_status=approval.status,
            assigned_to=approval.assigned_to,
            case_id=case.id,
            case_status=case.status.value,
            evidence_ids=evidence_ids,
        )

    except Exception:
        db.rollback()
        raise
